import{chromium}from'playwright-core';
import{spawn}from'node:child_process';
import{mkdir}from'node:fs/promises';
import{existsSync}from'node:fs';
import assert from'node:assert/strict';
const exe=process.env.CHROME_PATH||['C:/Program Files/Google/Chrome/Application/chrome.exe','/usr/bin/google-chrome','/usr/bin/chromium'].find(existsSync);
if(!exe)throw Error('Set CHROME_PATH to installed Chrome');
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4174','--strictPort'],{stdio:'pipe',windowsHide:true});
let browser;
try{
  await new Promise((res,rej)=>{server.stdout.on('data',d=>{if(String(d).includes('4174'))res();});server.once('error',rej);server.once('exit',code=>rej(Error(`Preview exited: ${code}`)));});
  browser=await chromium.launch({executablePath:exe,headless:true});
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('favicon'))errors.push(message.text());});
  await page.addInitScript(()=>{Math.random=()=>.4;});
  await page.goto('http://127.0.0.1:4174');
  await page.locator('#home').waitFor({state:'visible'});
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('.miniature-scene img').evaluate(img=>img.decode());
  assert.equal(await page.locator('.miniature-scene img').evaluate(img=>img.naturalWidth>0),true);
  await mkdir('out/qa',{recursive:true});
  await page.screenshot({path:'out/qa/home-desktop.png',fullPage:true});
  const ready=async()=>{if(await page.locator('#reveal-controls').isVisible())await page.locator('#reveal-controls').click();};
  const setup=async()=>page.locator('#configure').click();
  const done=async()=>page.locator('#apply-setup').click();
  await page.locator('#start').click();
  assert.equal(await page.locator('.lobby-nav').isVisible(),false);
  for(let i=0;i<3;i++){
    await ready();await page.locator('[data-move=scissors]').click();
    if(i===0){await page.locator('#pause').click();await page.waitForTimeout(800);assert.equal(await page.locator('#resolution').isVisible(),false);await page.locator('#modal-close').click();}
    await page.locator('#next').waitFor({state:'visible'});await page.locator('#next').click();
  }
  await page.locator('#result').waitFor({state:'visible'});
  assert.match(await page.locator('#result-title').innerText(),/بازیکن ۱/);
  assert.match(await page.locator('#save-status').innerText(),/ذخیره شد/);
  assert.equal(await page.locator('#battle-log p').count(),3);
  await page.screenshot({path:'out/qa/result-desktop.png',fullPage:true});
  await page.locator('#again').click();await page.locator('#game').waitFor({state:'visible'});await page.locator('#exit').click();await page.locator('#modal-exit').click();await page.locator('#scores').click();
  assert.match(await page.locator('#score-list').innerText(),/۵۷۵/);
  await page.reload();await page.locator('#home').waitFor({state:'visible'});assert.equal(await page.locator('#best').innerText(),'۵۷۵');
  await page.locator('[data-mode=party]').click();await setup();await page.locator('#player-count').selectOption('3');await page.locator('[data-bot="1"]').uncheck();await done();
  assert.match(await page.locator('#lobby-summary').innerText(),/۲ انسان/);
  await page.locator('#start').click();await ready();await page.locator('[data-move=back]').click();
  assert.equal(await page.locator('#choices').isVisible(),false);assert.equal(await page.locator('.hand').first().innerText(),'؟');
  await ready();await page.locator('[data-move=palm]').click();await page.locator('#next').waitFor({state:'visible'});
  assert.match(await page.locator('#round-result').innerText(),/بازیکن ۱ تک شد/);
  await page.screenshot({path:'out/qa/party-desktop.png',fullPage:true});
  await page.locator('#next').click();await ready();await page.locator('[data-move=scissors]').click();await page.locator('#next').waitFor({state:'visible'});await page.locator('#next').click();
  await page.locator('#result').waitFor({state:'visible'});assert.match(await page.locator('#result-title').innerText(),/بازیکن ۲/);
  await page.locator('.back-home').first().click();await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'out/qa/home-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#nav-players').click();await page.screenshot({path:'out/qa/setup-mobile.png',fullPage:true});await page.locator('#close-setup').click();
  await page.locator('#start').click();await page.locator('#pause').click();assert.equal(await page.locator('#modal').isVisible(),true);await page.locator('#modal-close').click();
  await page.screenshot({path:'out/qa/game-mobile.png',fullPage:true});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#exit').click();await page.locator('#modal-exit').click();await setup();await page.locator('#player-count').selectOption('8');await page.locator('[data-name="0"]').fill('<img src=x onerror=x()>');await done();
  await page.locator('#start').click();assert.equal(await page.locator('.hand-seat').count(),8);assert.equal(await page.locator('#table img').count(),0);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'out/qa/party-eight-mobile.png',fullPage:true});assert.deepEqual(errors,[]);
  console.log('Browser passed: miniature image, quick play, lobby navigation and setup, RPS, persistence, secret human choices, party elimination/final duel, pause, result log, 3/8-player mobile layout, safe names.');
}finally{await browser?.close();server.kill();}
